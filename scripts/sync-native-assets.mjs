/**
 * Sync configuration/webview.json and hybrid-jssdk host build into native packages.
 *
 * Usage (repo root):
 *   node scripts/sync-native-assets.mjs
 *
 * Requires hybrid-jssdk/dist/web-view-host.min.js (run: cd hybrid-jssdk && pnpm build).
 */
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(__dirname, '..')

const CONFIG_SRC = resolve(repoRoot, 'configuration/webview.json')
const HOST_SRC = resolve(repoRoot, 'hybrid-jssdk/dist/web-view-host.min.js')
const APIS_SRC = resolve(repoRoot, 'jssdk/apis.json')

const CONFIG_TARGETS = [
  'native/android/app/src/main/assets/configuration/webview.json',
  'native/ios/ios/configuration/webview.json',
  'native/macOS/macOS/configuration/webview.json',
  'native/ohos/entry/src/main/resources/rawfile/configuration/webview.json',
  'native/wechat-miniapp/miniprogram/configuration/webview.json',
]

const HOST_TARGETS = [
  'native/android/app/src/main/assets/sdk/web-view-host.min.js',
  'native/ios/ios/sdk/web-view-host.min.js',
  'native/macOS/macOS/sdk/web-view-host.min.js',
  'native/ohos/entry/src/main/resources/rawfile/sdk/web-view-host.min.js',
]

const APIS_TARGETS = [
  'native/android/app/src/main/assets/configuration/jssdk-apis.json',
  'native/ios/ios/configuration/jssdk-apis.json',
  'native/macOS/macOS/configuration/jssdk-apis.json',
  'native/ohos/entry/src/main/resources/rawfile/configuration/jssdk-apis.json',
  'native/wechat-miniapp/miniprogram/configuration/jssdk-apis.json',
]

function ensureParent(filePath) {
  mkdirSync(dirname(filePath), { recursive: true })
}

function copyFile(src, relDest) {
  const dest = resolve(repoRoot, relDest)
  ensureParent(dest)
  cpSync(src, dest)
  console.log(`copied -> ${relative(repoRoot, dest)}`)
}

function assertConfigShape(config) {
  if (!config || typeof config.url !== 'string' || !config.url) {
    throw new Error('configuration/webview.json: missing required string field "url"')
  }
  if (!Array.isArray(config.allowedHosts) || config.allowedHosts.length === 0) {
    throw new Error('configuration/webview.json: "allowedHosts" must be a non-empty string array')
  }

  let host = ''
  try {
    host = new URL(config.url).hostname.toLowerCase()
  } catch {
    throw new Error(`configuration/webview.json: invalid url "${config.url}"`)
  }

  const allowed = new Set(config.allowedHosts.map((h) => String(h).toLowerCase()))
  if (!allowed.has(host)) {
    throw new Error(
      `configuration/webview.json: url host "${host}" is not in allowedHosts`,
    )
  }
}

function main() {
  if (!existsSync(CONFIG_SRC)) {
    throw new Error(`Missing ${CONFIG_SRC}`)
  }

  const raw = readFileSync(CONFIG_SRC, 'utf8')
  const config = JSON.parse(raw)
  assertConfigShape(config)

  const normalized = `${JSON.stringify(config, null, 2)}\n`

  for (const rel of CONFIG_TARGETS) {
    const dest = resolve(repoRoot, rel)
    ensureParent(dest)
    writeFileSync(dest, normalized)
    console.log(`wrote  -> ${relative(repoRoot, dest)}`)
  }

  const wechatJs = resolve(
    repoRoot,
    'native/wechat-miniapp/miniprogram/configuration/webview.js',
  )
  ensureParent(wechatJs)
  writeFileSync(
    wechatJs,
    `/** Auto-generated by scripts/sync-native-assets.mjs — do not edit. */\nmodule.exports = ${JSON.stringify(config, null, 2)}\n`,
  )
  console.log(`wrote  -> ${relative(repoRoot, wechatJs)}`)

  if (existsSync(APIS_SRC)) {
    const apisRaw = readFileSync(APIS_SRC, 'utf8')
    const apisNormalized = `${JSON.stringify(JSON.parse(apisRaw), null, 2)}\n`
    for (const rel of APIS_TARGETS) {
      const dest = resolve(repoRoot, rel)
      ensureParent(dest)
      writeFileSync(dest, apisNormalized)
      console.log(`wrote  -> ${relative(repoRoot, dest)}`)
    }
  } else {
    console.warn(`Skip apis sync: missing ${relative(repoRoot, APIS_SRC)}`)
  }

  if (!existsSync(HOST_SRC)) {
    console.warn(
      `Skip host sync: missing ${relative(repoRoot, HOST_SRC)} (run: cd hybrid-jssdk && pnpm build)`,
    )
    return
  }

  for (const rel of HOST_TARGETS) {
    copyFile(HOST_SRC, rel)
  }
}

main()
